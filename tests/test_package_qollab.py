"""Tests for the script that builds the project that is uploaded to Qollab."""

from __future__ import annotations

import importlib.util
import re
import shutil
import subprocess
from pathlib import Path

import pytest

_ROOT = Path(__file__).parent.parent
_SCRIPT = _ROOT / "scripts" / "package_qollab.py"


@pytest.fixture(scope="module")
def module():
    spec = importlib.util.spec_from_file_location("package_qollab", _SCRIPT)
    loaded = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(loaded)
    return loaded


@pytest.fixture(scope="module")
def packaged(module, tmp_path_factory):
    out = tmp_path_factory.mktemp("viewer")
    files = {path.as_posix() for path in module.package(out)}
    return out, files


def test_the_project_fits_in_the_qollab_limit(module, packaged):
    out, files = packaged
    assert len(files) <= module.MAX_FILES
    assert all((out / name).is_file() for name in files)


def test_it_is_a_js_project_without_main_py(packaged):
    _, files = packaged
    assert {"index.html", "main.js", "qollab_api.py", "requirements.txt"} <= files
    assert "main.py" not in files


def test_the_mit_license_is_in_the_repository_and_in_the_project(packaged):
    _, files = packaged
    assert "LICENSE" in files
    text = (_ROOT / "LICENSE").read_text(encoding="utf-8")
    assert text.startswith("MIT License") and "Permission is hereby granted" in text


def test_the_libraries_are_complete(packaged):
    _, files = packaged
    assert "backend/__init__.py" in files
    assert "backend/core/sampler/sampler.py" in files
    assert "examples/__init__.py" in files
    assert not any("__pycache__" in name for name in files)


def test_the_viewer_package_is_the_real_viewer(packaged):
    out, files = packaged
    assert "main.css" in files
    html = (out / "index.html").read_text(encoding="utf-8")
    assert "<script" not in html, "Qollab runs no script of the HTML"
    assert 'id="measure"' in html and 'id="stage"' in html

    source = (_ROOT / "frontend" / "index.html").read_text(encoding="utf-8")
    style = source.split("<style>")[1].split("</style>")[0]
    assert (out / "main.css").read_text(encoding="utf-8").strip() == style.strip()

    # Qollab serves no other file of the project: the modules go inside main.js.
    assert not any(name.startswith("js/") for name in files)
    js = (out / "main.js").read_text(encoding="utf-8")
    for path in sorted((_ROOT / "frontend" / "js").glob("*.js")):
        assert f"// ---- {path.name}\n" in js, path.name
    assert not re.search(r"^import .* from [\"']\.", js, re.M), "relative import"
    assert 'import("./js' not in js and "from './" not in js


def test_the_viewer_gets_its_shaders_and_the_qollab_services(packaged):
    out, _ = packaged
    js = (out / "main.js").read_text(encoding="utf-8")
    assert js.startswith("// Generated by scripts/package_qollab.py")
    assert 'from "qollab_api"' in js
    assert "gl_FragColor" in js and "instancePsi" in js, "shaders are embedded"
    assert "uLocalCenter" in js, "the lens shaders are embedded"
    assert "uLaserActive" in js, "the laser beam shaders are embedded"
    assert "vLocalPos" in js, "the phonon bus shaders are embedded"
    assert "uActiveHalf" in js, "the phonon guide rail shaders are embedded"
    assert "newmtl" in js and "\\nv " in js, "the laser model is embedded"
    assert "window.QVIZ_HOST" in js

    for name in ("OBJLoader", "RoomEnvironment", "BufferGeometryUtils"):
        assert f"const {{ {name} }}" in js or f"const {name} =" in js, name
    assert js.count('import * as THREE from "three";') == 1


def test_every_service_of_the_prelude_is_used_by_the_viewer(module):
    prelude = module._PRELUDE
    host = prelude.split("window.QVIZ_HOST = {")[1]
    services = re.findall(r"^\s{4}(\w+):", host, re.M)
    assert {"circuits", "load", "sample"} <= set(services)

    viewer = (_ROOT / "frontend" / "index.html").read_text(encoding="utf-8")
    for path in sorted((_ROOT / "frontend" / "js").glob("*.js")):
        viewer += path.read_text(encoding="utf-8")
    for service in services:
        assert f"HOST.{service}" in viewer, f"the viewer ignores HOST.{service}"
    assert "shaders:" in prelude and "HOST.shaders" in viewer


def test_every_python_function_of_the_prelude_exists_in_the_api(module):
    import qollab_api

    called = set(re.findall(r"api\.(\w+)\.callPromising", module._PRELUDE))
    assert {"circuits", "run", "run_qasm", "sample_step"} <= called
    for name in called:
        assert callable(getattr(qollab_api, name)), name


@pytest.mark.skipif(shutil.which("node") is None, reason="node is not installed")
def test_the_generated_script_is_valid_javascript(packaged, tmp_path):
    out, _ = packaged
    module_file = tmp_path / "main.mjs"
    module_file.write_bytes((out / "main.js").read_bytes())
    result = subprocess.run(
        ["node", "--check", str(module_file)], capture_output=True, text=True
    )
    assert result.returncode == 0, result.stderr


def test_the_bundler_keeps_the_scope_of_each_module(module):
    modules = {
        "main": 'import { run } from "./a.js";\nimport * as b from "./b.js";\n'
        "run(b.value);\n",
        "a": 'import * as THREE from "three";\nimport { value as v } from "./b.js";\n'
        "const secret = 1;\nexport function run(x) { return [THREE, v, x, secret]; }\n",
        "b": 'import * as THREE from "three";\nconst secret = 2;\n'
        "export const value = secret;\nexport const { first, second: other } = { };\n",
    }
    code = module.bundle_modules(modules)
    assert code.count('import * as THREE from "three";') == 1
    assert "const { value: v } = __module_b;" in code
    assert "const b = __module_b;" in code
    assert "return { value, first, other };" in code
    # Both modules declare `secret`: only separate scopes make that valid.
    assert code.count("const secret") == 2
    assert code.index("// ---- b.js") < code.index("// ---- a.js")
    assert code.index("// ---- a.js") < code.index("// ---- main.js")
    assert "import {" not in code.replace("import * as THREE", "")


def test_the_bundler_rejects_what_it_cannot_follow(module):
    with pytest.raises(SystemExit):
        module.bundle_modules({"main": "export default 1;\n"})
    with pytest.raises(SystemExit):
        module.bundle_modules({"main": 'import x from "./main.js";\n'})
