"""Tests for the script that builds the project that is uploaded to Qollab."""

from __future__ import annotations

import importlib.util
import re
import shutil
import subprocess
from pathlib import Path

import pytest

_ROOT = Path(__file__).parent.parent
_SCRIPT = _ROOT / "scripts" / "package_qollab.py"


@pytest.fixture(scope="module")
def module():
    spec = importlib.util.spec_from_file_location("package_qollab", _SCRIPT)
    loaded = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(loaded)
    return loaded


@pytest.fixture(scope="module", params=["viewer", "probe"])
def packaged(request, module, tmp_path_factory):
    out = tmp_path_factory.mktemp(request.param)
    files = {str(path) for path in module.package(out, request.param)}
    return request.param, out, files


def test_the_project_fits_in_the_qollab_limit(module, packaged):
    _, out, files = packaged
    assert len(files) <= module.MAX_FILES
    assert all((out / name).is_file() for name in files)


def test_it_is_a_js_project_without_main_py(packaged):
    _, _, files = packaged
    assert {"index.html", "main.js", "qollab_api.py", "requirements.txt"} <= files
    assert "main.py" not in files


def test_the_libraries_are_complete(packaged):
    _, _, files = packaged
    assert "backend/__init__.py" in files
    assert "backend/core/sampler/sampler.py" in files
    assert "examples/__init__.py" in files
    assert not any("__pycache__" in name for name in files)


def test_an_unknown_page_is_rejected(module, tmp_path):
    with pytest.raises(SystemExit):
        module.package(tmp_path / "x", "nope")


def test_the_viewer_package_is_the_real_viewer(packaged):
    page, out, files = packaged
    if page != "viewer":
        pytest.skip("only for the viewer")
    assert "main.css" in files
    html = (out / "index.html").read_text()
    assert "<script" not in html, "Qollab runs no script of the HTML"
    assert 'id="measure"' in html and 'id="stage"' in html

    source = (_ROOT / "frontend" / "index.html").read_text()
    style = source.split("<style>")[1].split("</style>")[0]
    assert (out / "main.css").read_text().strip() == style.strip()

    # The modules of the viewer are copied as they are.
    entry = (_ROOT / "frontend" / "js" / "main.js").read_text()
    assert (out / "js" / "main.js").read_text() == entry
    assert {"js/main.js", "js/scene.js", "js/three-addons.js"} <= files


def test_the_viewer_gets_its_shaders_and_the_qollab_services(packaged):
    page, out, _ = packaged
    if page != "viewer":
        pytest.skip("only for the viewer")
    js = (out / "main.js").read_text()
    assert js.startswith("// Generated by scripts/package_qollab.py")
    assert 'from "qollab_api"' in js
    assert "gl_FragColor" in js and "instancePsi" in js, "shaders are embedded"
    assert "uLocalCenter" in js, "the lens shaders are embedded"
    assert "newmtl" in js and "\\nv " in js, "the laser model is embedded"
    assert "window.QVIZ_HOST" in js
    assert 'import("./js/main.js")' in js

    addons = (out / "js" / "three-addons.js").read_text()
    for name in ("OBJLoader", "RoomEnvironment", "BufferGeometryUtils"):
        assert name in addons, name
    assert 'from "three"' in (out / "js" / "scene.js").read_text()


def test_every_service_of_the_prelude_is_used_by_the_viewer(module):
    prelude = module._PRELUDE
    host = prelude.split("window.QVIZ_HOST = {")[1]
    services = re.findall(r"^\s{4}(\w+):", host, re.M)
    assert {"circuits", "load", "sample"} <= set(services)

    viewer = (_ROOT / "frontend" / "index.html").read_text()
    for path in sorted((_ROOT / "frontend" / "js").glob("*.js")):
        viewer += path.read_text()
    for service in services:
        assert f"HOST.{service}" in viewer, f"the viewer ignores HOST.{service}"
    assert "shaders:" in prelude and "HOST.shaders" in viewer


def test_every_python_function_of_the_prelude_exists_in_the_api(module):
    import qollab_api

    called = set(re.findall(r"api\.(\w+)\.callPromising", module._PRELUDE))
    assert {"circuits", "run", "run_qasm", "sample_step"} <= called
    for name in called:
        assert callable(getattr(qollab_api, name)), name


@pytest.mark.skipif(shutil.which("node") is None, reason="node is not installed")
def test_the_generated_script_is_valid_javascript(packaged, tmp_path):
    _, out, _ = packaged
    module_file = tmp_path / "main.mjs"
    module_file.write_text((out / "main.js").read_text())
    result = subprocess.run(
        ["node", "--check", str(module_file)], capture_output=True, text=True
    )
    assert result.returncode == 0, result.stderr
