"""Build ``qollab/``, the JS project that is uploaded to Qollab.

The whole repository is more than Qollab accepts (100 files per project, and an
upload over the limit is rejected completely), and Qollab only looks at the
files of the root to decide the type of the project. Qollab also runs no
``<script>`` of the HTML, loads a single style sheet (``main.css``) and cannot
read the files of the project from JS. This script builds the project from the
repository: the real viewer, ``frontend/index.html``. Its markup becomes
``index.html`` and its style ``main.css``. ``main.js`` is generated: a short
prelude that gives the viewer the Qollab services (``window.QVIZ_HOST``) followed
by **all the modules of** ``frontend/js`` **bundled in one file**. Qollab does not
serve the other files of the project, so a relative ``import("./js/main.js")``
fails there (``error loading dynamically imported module``). The project also
has ``qollab_api.py``, ``requirements.txt``, the ``LICENSE`` (MIT) and the
libraries ``backend/`` and ``examples/``. ``main.py`` is left out on purpose: in
a JS project it could compile a second time and spend a second IonQ job.

Upload the **content** of ``qollab/``. See ``documentation/prompts/qollab_pruebas.md``.

Run with: python scripts/package_qollab.py   (or: make qollab)
"""

from __future__ import annotations

import json
import re
import shutil
from collections.abc import Iterator
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "qollab"
MAX_FILES = 100
MAX_BYTES = 2_000_000

_LIBRARY = ("backend", "examples")
_SHARED = ("qollab_api.py", "requirements.txt", "LICENSE")
_VIEWER = Path("frontend") / "index.html"
_VIEWER_MODULES = Path("frontend") / "js"
_ENTRY_IMPORT = "./js/main.js"
_SHADERS = Path("shaders")
_MODELS = Path("models")

# The prelude runs before the modules, so that `window.QVIZ_HOST` is ready when
# the modules read it. It provides the shaders, the laser model, the circuits,
# the compilation and the measurement of the backend. The modules import three
# and three/addons by name, which Qollab resolves.
_PRELUDE = """\
// Generated by scripts/package_qollab.py from frontend/index.html and frontend/js.
// Do not edit: change the viewer and run `make qollab` again.
import * as api from "qollab_api";

// The text of each JSON, to send it to Python without writing it again.
const sources = new WeakMap();
const textOf = (data) => {
  if (!sources.has(data)) sources.set(data, JSON.stringify(data));
  return sources.get(data);
};

// Python errors reach JS with their whole traceback. The errors of QViz are meant
// to be read, so only their message is kept; any other error is left untouched.
const readable = (error) => {
  const last = String(error && error.message).trim().split("\\n").pop();
  const prefix = "backend.core.errors.";
  const colon = last.indexOf(": ");
  const ours = last.startsWith(prefix) && colon > 0;
  return ours ? new Error(last.slice(colon + 2)) : error;
};

try {
  window.QVIZ_HOST = {
    shaders: __SHADERS__,
    laser: __LASER__,
    circuits: JSON.parse(await api.circuits.callPromising()),
    // Compiles an example circuit on the backend of Qollab. IonQ allows one job
    // per run, so only the first compilation works there.
    load: async (name) => {
      let text;
      try {
        text = await api.run.callPromising(backend, name, 1024, "auto");
      } catch (error) {
        throw readable(error);
      }
      const data = JSON.parse(text);
      sources.set(data, text);
      return data;
    },
    // Compiles a circuit written in OpenQASM 2 or 3. It is transpiled locally,
    // so it never sends the IonQ job and any number of files can be loaded.
    compileQasm: async (text) => {
      let json;
      try {
        json = await api.run_qasm.callPromising(backend, text, 1024, "auto");
      } catch (error) {
        throw readable(error);
      }
      const data = JSON.parse(json);
      sources.set(data, json);
      return data;
    },
    // Measures a step with the statevector of the backend; no job is sent.
    sample: async (data, step, shots) => {
      try {
        const text = await api.sample_step.callPromising(textOf(data), step, shots);
        return JSON.parse(text);
      } catch (error) {
        throw readable(error);
      }
    },
  };
} catch (error) {
  document.getElementById("error").textContent =
    "No se pudo conectar con Python: " + error.message;
}
"""


def _between(text: str, start: str, end: str, after: int = 0) -> tuple[str, int]:
    """Return the text between two markers and the position after the second."""
    begin = text.index(start, after) + len(start)
    stop = text.index(end, begin)
    return text[begin:stop], stop + len(end)


_MODULE_SCRIPT = re.compile(r'<script type="module"[^>]*>')


def split_viewer(html: str) -> tuple[str, str]:
    """Return the style and the markup of the viewer, and check the entry."""
    style, _ = _between(html, "<style>", "</style>")
    body_start = html.index("<body>") + len("<body>")
    opening = _MODULE_SCRIPT.search(html, body_start)
    if opening is None:
        raise SystemExit('the viewer has no <script type="module"> in its body')
    markup = html[body_start : opening.start()]
    if _ENTRY_IMPORT not in opening.group():
        raise SystemExit(f"the viewer module script must load {_ENTRY_IMPORT}")
    return style.strip(), markup.strip()


# The bundler below is deliberately small. It does not parse JavaScript: it only
# understands the style of frontend/js (``export`` in front of a declaration, and
# ``import {a, b as c}`` or ``import * as x`` from a relative path) and refuses
# anything else, so a change of style fails when the project is built, not on
# Qollab. Why bundle at all: Qollab serves no file of the project besides the
# ones it loads itself, so a relative ``import("./js/main.js")`` fails there.
_IMPORT = re.compile(
    r"^import\s+([^\"';]*?)\s+from\s+[\"']([^\"']+)[\"'];?[ \t]*\n", re.M
)
_EXPORT_DECLARATION = re.compile(
    r"^export\s+(?:async\s+function|function|class|const|let|var)\s+(\w+)", re.M
)
_EXPORT_DESTRUCTURING = re.compile(r"^export\s+(?:const|let|var)\s+\{([^}]*)\}", re.M)


def _module_order(modules: dict[str, str], name: str, seen: set[str]) -> Iterator[str]:
    """Yield the modules reachable from ``name``, each after what it imports."""
    if name in seen:
        return
    seen.add(name)
    for _, path in _IMPORT.findall(modules[name]):
        if path.startswith("."):
            yield from _module_order(modules, Path(path).stem, seen)
    yield name


def _variable(name: str) -> str:
    """Return the variable that holds what the module ``name`` exports."""
    return "__module_" + re.sub(r"\W", "_", name)


def _exported_names(source: str) -> list[str]:
    if re.search(r"^export\s+(default\b|\{)", source, re.M):
        raise SystemExit("the viewer modules may only use `export <declaration>`")
    names = _EXPORT_DECLARATION.findall(source)
    for group in _EXPORT_DESTRUCTURING.findall(source):
        names += [part.strip().split(":")[-1].strip() for part in group.split(",")]
    return [name for name in names if name]


def bundle_modules(modules: dict[str, str], entry: str = "main") -> str:
    """Return the modules of the viewer as one script, without relative imports.

    ``modules`` maps a module name (``scene`` for ``scene.js``) to its source.
    Each module becomes an ``async`` function with its own scope, so two modules
    may declare the same private name; what it exports is returned as an object
    and the importers destructure it. The imports of other packages (``three``)
    are not touched: they are collected, repeated ones dropped, and put first.
    """
    external: list[str] = []
    parts: list[str] = []
    for name in _module_order(modules, entry, set()):
        source = modules[name]

        def replace(match: re.Match[str], name: str = name) -> str:
            clause, path = match.group(1).strip(), match.group(2)
            if not path.startswith("."):
                statement = f'import {" ".join(clause.split())} from "{path}";'
                if statement not in external:
                    external.append(statement)
                return ""
            target = _variable(Path(path).stem)
            if clause.startswith("{"):
                return f"const {clause.replace(' as ', ': ')} = {target};\n"
            if clause.startswith("* as "):
                return f"const {clause[5:].strip()} = {target};\n"
            raise SystemExit(f"unsupported import in {name}.js: {clause!r}")

        body = _IMPORT.sub(replace, source)
        names = _exported_names(source)
        body = re.sub(r"^export\s+", "", body, flags=re.M)
        parts.append(
            f"// ---- {name}.js\n"
            f"const {_variable(name)} = await (async () => {{\n{body.strip()}\n"
            f"return {{ {', '.join(names)} }};\n}})();\n"
        )
    if re.search(r"^\s*import\s+[^(]", "".join(parts), re.M):
        raise SystemExit("an import of the viewer was not bundled")
    return "\n".join(external) + "\n\n" + "\n".join(parts)


def _read(path: Path) -> str:
    """Return the text of a file of the repository."""
    return (ROOT / path).read_text(encoding="utf-8")


def viewer_files() -> dict[str, str]:
    """Return the three files of the viewer project, keyed by their name."""
    style, markup = split_viewer(_read(_VIEWER))
    shaders = {
        "vert": _read(_SHADERS / "bloch.vert"),
        "frag": _read(_SHADERS / "bloch.frag"),
        "lensVert": _read(_SHADERS / "lens.vert"),
        "lensFrag": _read(_SHADERS / "lens.frag"),
        "laserVert": _read(_SHADERS / "laser.vert"),
        "laserFrag": _read(_SHADERS / "laser.frag"),
        "busVert": _read(_SHADERS / "bus.vert"),
        "busFrag": _read(_SHADERS / "bus.frag"),
        "railVert": _read(_SHADERS / "rail.vert"),
        "railFrag": _read(_SHADERS / "rail.frag"),
    }
    laser = {
        "obj": _read(_MODELS / "laser_lens.obj"),
        "mtl": _read(_MODELS / "laser_lens.mtl"),
    }
    prelude = _PRELUDE.replace("__SHADERS__", json.dumps(shaders)).replace(
        "__LASER__", json.dumps(laser)
    )
    modules = {
        path.stem: path.read_text(encoding="utf-8")
        for path in sorted((ROOT / _VIEWER_MODULES).glob("*.js"))
    }
    return {
        "index.html": markup + "\n",
        "main.css": style + "\n",
        "main.js": prelude + "\n" + bundle_modules(modules),
    }


def _library_files() -> list[Path]:
    """Return the paths, relative to the root, of the library and shared files."""
    files = [Path(name) for name in _SHARED]
    for folder in _LIBRARY:
        files += sorted(
            path.relative_to(ROOT)
            for path in (ROOT / folder).rglob("*")
            if path.is_file()
            and "__pycache__" not in path.parts
            and path.suffix != ".pyc"
        )
    return files


def package(out_dir: Path = OUT) -> list[Path]:
    """Write the project folder and return its files, as paths inside it."""
    if out_dir.exists():
        shutil.rmtree(out_dir)
    out_dir.mkdir(parents=True)

    written = []
    for source in _library_files():
        destination = out_dir / source
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(ROOT / source, destination)
        written.append(source)

    for name, content in viewer_files().items():
        destination = out_dir / name
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(content, encoding="utf-8")
        written.append(Path(name))

    too_big = [str(p) for p in written if (out_dir / p).stat().st_size > MAX_BYTES]
    if len(written) > MAX_FILES or too_big:
        raise SystemExit(f"{len(written)} files (max {MAX_FILES}); too big: {too_big}")
    return written


def main() -> None:
    """Build the folder and print what to upload."""
    files = package()
    print(f"qollab/: {len(files)} files (limit {MAX_FILES})")
    print("Upload the content of qollab/ (not the folder itself) as a JS project.")


if __name__ == "__main__":
    main()
