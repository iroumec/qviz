"""Build ``qollab/``, the JS project that is uploaded to Qollab.

The whole repository is more than Qollab accepts (100 files per project, and an
upload over the limit is rejected completely), and Qollab only looks at the
files of the root to decide the type of the project. Qollab also runs no
``<script>`` of the HTML, loads a single style sheet (``main.css``) and cannot
read the files of the project from JS. This script builds the project from the
repository:

- ``viewer`` (default): the real viewer, ``frontend/index.html``. Its markup
  becomes ``index.html``, its style ``main.css`` and its script ``main.js``, with
  a short prelude that gives it the Qollab services (``window.QVIZ_HOST``): the
  shaders, the laser model, the circuits, the compilation and the measurement of
  the backend. The viewer itself is copied as it is (only its ``import`` lines
  move to the prelude), so its look does not change.
- ``probe``: the test page of ``scripts/qollab_js_probe`` (Compile, Measure and
  Run checks), to diagnose the connection with Python.

Both include ``qollab_api.py``, ``requirements.txt`` and the libraries
``backend/`` and ``examples/``. ``main.py`` is left out on purpose: in a JS
project it could compile a second time and spend a second IonQ job.

Upload the **content** of ``qollab/``. See ``documentation/prompts/qollab_pruebas.md``.

Run with: python scripts/package_qollab.py [viewer|probe]   (or: make qollab)
"""

from __future__ import annotations

import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "qollab"
MAX_FILES = 100
MAX_BYTES = 2_000_000

_LIBRARY = ("backend", "examples")
_SHARED = ("qollab_api.py", "requirements.txt")
_PROBE = Path("scripts") / "qollab_js_probe"
_VIEWER = Path("frontend") / "index.html"
_SHADERS = Path("shaders")
_MODELS = Path("models")
PAGES = ("viewer", "probe")

# The viewer is an ES module that imports three.js and three/addons from an
# import map, which Qollab does not read. The prelude imports them instead (the
# ``import`` lines of the viewer are removed) and gives the same names. The addons
# are loaded apart so that, if Qollab cannot resolve them, the viewer still works
# without the laser and the environment light instead of not starting.
_PRELUDE = """\
// Generated by scripts/package_qollab.py from frontend/index.html. Do not edit:
// change the viewer and run `make qollab` again.
import * as THREE from "three";
import * as api from "qollab_api";

const addon = async (load, fallback) => {
  try {
    return await load();
  } catch (error) {
    console.warn("QViz: a three.js addon could not be loaded", error);
    return fallback;
  }
};
const { OBJLoader } = await addon(
  () => import("three/addons/loaders/OBJLoader.js"),
  {
    OBJLoader: class {
      load(url, onLoad, onProgress, onError) {
        onError(new Error("OBJLoader is not available"));
      }
      parse() {
        throw new Error("OBJLoader is not available");
      }
    },
  },
);
const { RoomEnvironment } = await addon(
  () => import("three/addons/environments/RoomEnvironment.js"),
  { RoomEnvironment: class extends THREE.Scene { dispose() {} } },
);
const BufferGeometryUtils = await addon(
  () => import("three/addons/utils/BufferGeometryUtils.js"),
  {},
);

// The text of each JSON, to send it to Python without writing it again.
const sources = new WeakMap();
const textOf = (data) => {
  if (!sources.has(data)) sources.set(data, JSON.stringify(data));
  return sources.get(data);
};

// Python errors reach JS with their whole traceback. The errors of QViz are meant
// to be read, so only their message is kept; any other error is left untouched.
const readable = (error) => {
  const last = String(error && error.message).trim().split("\\n").pop();
  const prefix = "backend.core.errors.";
  const colon = last.indexOf(": ");
  const ours = last.startsWith(prefix) && colon > 0;
  return ours ? new Error(last.slice(colon + 2)) : error;
};

try {
  window.QVIZ_HOST = {
    shaders: __SHADERS__,
    laser: __LASER__,
    circuits: JSON.parse(await api.circuits.callPromising()),
    // Compiles an example circuit on the backend of Qollab. IonQ allows one job
    // per run, so only the first compilation works there.
    load: async (name) => {
      let text;
      try {
        text = await api.run.callPromising(backend, name, 1024, "auto");
      } catch (error) {
        throw readable(error);
      }
      const data = JSON.parse(text);
      sources.set(data, text);
      return data;
    },
    // Measures a step with the statevector of the backend; no job is sent.
    sample: async (data, step, shots) => {
      try {
        const text = await api.sample_step.callPromising(textOf(data), step, shots);
        return JSON.parse(text);
      } catch (error) {
        throw readable(error);
      }
    },
  };
} catch (error) {
  document.getElementById("error").textContent =
    "No se pudo conectar con Python: " + error.message;
}

"""


def _between(text: str, start: str, end: str, after: int = 0) -> tuple[str, int]:
    """Return the text between two markers and the position after the second."""
    begin = text.index(start, after) + len(start)
    stop = text.index(end, begin)
    return text[begin:stop], stop + len(end)


_MODULE_SCRIPT = re.compile(r'<script type="module">')
_IMPORT = re.compile(r"^import .+ from ['\"]three(?:/[^'\"]*)?['\"];?[ \t]*\n", re.M)


def split_viewer(html: str) -> tuple[str, str, str]:
    """Return the style, the markup and the script (without its imports)."""
    style, _ = _between(html, "<style>", "</style>")
    body_start = html.index("<body>") + len("<body>")
    opening = _MODULE_SCRIPT.search(html, body_start)
    if opening is None:
        raise SystemExit('the viewer has no <script type="module"> in its body')
    markup = html[body_start : opening.start()]
    script, _ = _between(html, opening.group(), "</script>", body_start)
    script = _IMPORT.sub("", script)
    if re.search(r"^\s*import\b", script, re.M):
        raise SystemExit("the viewer imports something the prelude does not give")
    return style.strip(), markup.strip(), script.strip()


def _read(path: Path) -> str:
    """Return the text of a file of the repository."""
    return (ROOT / path).read_text(encoding="utf-8")


def viewer_files() -> dict[str, str]:
    """Return ``index.html``, ``main.css`` and ``main.js`` made from the viewer."""
    style, markup, script = split_viewer(_read(_VIEWER))
    shaders = {
        "vert": _read(_SHADERS / "bloch.vert"),
        "frag": _read(_SHADERS / "bloch.frag"),
        "lensVert": _read(_SHADERS / "lens.vert"),
        "lensFrag": _read(_SHADERS / "lens.frag"),
    }
    laser = {
        "obj": _read(_MODELS / "laser_lens.obj"),
        "mtl": _read(_MODELS / "laser_lens.mtl"),
    }
    prelude = _PRELUDE.replace(
        "__SHADERS__", json.dumps(shaders)
    ).replace("__LASER__", json.dumps(laser))
    return {
        "index.html": markup + "\n",
        "main.css": style + "\n",
        "main.js": prelude + script + "\n",
    }


def _library_files() -> list[Path]:
    """Return the paths, relative to the root, of the library and shared files."""
    files = [Path(name) for name in _SHARED]
    for folder in _LIBRARY:
        files += sorted(
            path.relative_to(ROOT)
            for path in (ROOT / folder).rglob("*")
            if path.is_file()
            and "__pycache__" not in path.parts
            and path.suffix != ".pyc"
        )
    return files


def package(out_dir: Path = OUT, page: str = "viewer") -> list[Path]:
    """Write the project folder and return its files, as paths inside it."""
    if page not in PAGES:
        raise SystemExit(f"page must be one of {', '.join(PAGES)}, got {page!r}")
    if out_dir.exists():
        shutil.rmtree(out_dir)
    out_dir.mkdir(parents=True)

    written = []
    for source in _library_files():
        destination = out_dir / source
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(ROOT / source, destination)
        written.append(source)

    if page == "viewer":
        for name, content in viewer_files().items():
            (out_dir / name).write_text(content, encoding="utf-8")
            written.append(Path(name))
    else:
        for name in ("index.html", "main.js"):
            shutil.copyfile(ROOT / _PROBE / name, out_dir / name)
            written.append(Path(name))

    too_big = [str(p) for p in written if (out_dir / p).stat().st_size > MAX_BYTES]
    if len(written) > MAX_FILES or too_big:
        raise SystemExit(f"{len(written)} files (max {MAX_FILES}); too big: {too_big}")
    return written


def main() -> None:
    """Build the folder and print what to upload."""
    page = sys.argv[1] if len(sys.argv) > 1 else "viewer"
    files = package(page=page)
    print(f"qollab/ ({page}): {len(files)} files (limit {MAX_FILES})")
    print("Upload the content of qollab/ (not the folder itself) as a JS project.")


if __name__ == "__main__":
    main()
